def get_burger_price_test_data():
    """Тестовые данные для расчета цены бургера"""
    return [
        (100, [100, 200], 500),        # 100*2 + 100 + 200 = 500
        (200, [150, 250, 300], 1100),  # 200*2 + 150 + 250 + 300 = 1100
        (150, [], 300),                # Только булочки: 150*2 = 300
        (180, [200], 560),             # 180*2 + 200 = 560
        (0, [100, 200], 300),          # Бесплатная булочка: 0*2 + 100 + 200 = 300
        (50, [0, 0], 100),             # Бесплатные ингредиенты: 50*2 + 0 + 0 = 100
    ]


